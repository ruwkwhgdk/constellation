const fs=require("fs"),assert=require("assert");
const {chromium}=require("C:/Users/User/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright");
(async()=>{
 const config=JSON.parse(fs.readFileSync("Saved/CombatAuthor/server.json","utf8"));
 const browser=await chromium.launch({channel:"msedge",headless:true});
 const page=await browser.newPage({viewport:{width:1600,height:1000}});
 const errors=[];page.on("pageerror",e=>errors.push(e.message));
 await page.goto(config.url);
 await page.locator("#versions").selectOption("CombatTool_v1");
 await page.locator("#clone").click();
 await page.getByRole("button",{name:"플레이어 · 슬롯",exact:true}).click();
 await page.getByLabel("최대 HP",{exact:true}).fill("135");
 await page.getByLabel("최대 HP",{exact:true}).press("Tab");
 assert.equal(await page.getByLabel("최대 HP",{exact:true}).inputValue(),"135");
 await page.locator("#undo").click();
 assert.equal(await page.getByLabel("최대 HP",{exact:true}).inputValue(),"100");
 await page.locator("#redo").click();
 assert.equal(await page.getByLabel("최대 HP",{exact:true}).inputValue(),"135");
 await page.locator("#validate").click();
 await page.locator("#message").filter({hasText:"JSON 검사 통과"}).waitFor();
 await page.getByRole("button",{name:"플레이어 액션",exact:true}).click();
 await page.locator("#search").fill("돌진");
 assert(await page.getByRole("heading",{name:"Dash",exact:true}).isVisible());
 await page.screenshot({path:"Saved/CombatAuthor/author-actions.png",fullPage:true});
 await page.getByRole("button",{name:"변경 내역",exact:true}).click();
 assert(await page.getByText("player.stats.max_health",{exact:true}).isVisible());
 await page.setViewportSize({width:1280,height:720});
 await page.screenshot({path:"Saved/CombatAuthor/author-changes-1280.png",fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 await browser.close();console.log("PASS: browser editing, undo/redo, validation, search, changes, 1280 layout");
})().catch(e=>{console.error(e);process.exit(1)});
